def get_mode(mode_id: str) -> FeedbackMode:
    """피드백 모드를 반환합니다. 없으면 코치 모드 기본값."""
    return FEEDBACK_MODES.get(mode_id, FEEDBACK_MODES["coach"])


def list_modes() -> list[dict]:
    """사용 가능한 피드백 모드 목록을 반환합니다."""
    return [
        {
            "mode_id": m.mode_id,
            "mode_name": m.mode_name,
            "emoji": m.emoji,
            "description": m.description,
        }
        for m in FEEDBACK_MODES.values()
    ]


def build_mode_prompt_prefix(mode: FeedbackMode) -> str:
    """LLM 프롬프트에 삽입할 모드별 페르소나+톤 지시를 생성합니다."""
    rules = "\n".join(f"  - {r}" for r in mode.style_rules)

    return f"""{mode.persona}

[출력 톤/스타일]
{mode.tone}

[스타일 규칙]
{rules}

[예시 - 긍정 상황]
{mode.example_positive}

[예시 - 부정 상황]
{mode.example_negative}
"""
